-- Version 1. Explicit PostgreSQL schema; epoch times remain DOUBLE PRECISION.
CREATE TABLE IF NOT EXISTS visitors (
                    id TEXT PRIMARY KEY, token_hash TEXT UNIQUE NOT NULL, created DOUBLE PRECISION NOT NULL);
                CREATE TABLE IF NOT EXISTS user_profiles (
                    owner TEXT PRIMARY KEY, nickname TEXT NOT NULL, age INTEGER,
                    bio TEXT NOT NULL, avatar BYTEA, revision INTEGER NOT NULL);
                CREATE TABLE IF NOT EXISTS assets (
                    book_id TEXT PRIMARY KEY, canonical TEXT NOT NULL,
                    source_hash TEXT NOT NULL, text_hash TEXT, catalog TEXT NOT NULL);
                CREATE INDEX IF NOT EXISTS assets_source ON assets(source_hash);
                CREATE INDEX IF NOT EXISTS assets_text ON assets(text_hash);
                CREATE TABLE IF NOT EXISTS library_books (
                    owner TEXT NOT NULL, canonical TEXT NOT NULL, added DOUBLE PRECISION NOT NULL,
                    PRIMARY KEY(owner, canonical));
                CREATE TABLE IF NOT EXISTS removed_books (
                    owner TEXT NOT NULL, canonical TEXT NOT NULL,
                    PRIMARY KEY(owner, canonical));
                CREATE TABLE IF NOT EXISTS resources (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL,
                    book_id TEXT NOT NULL, title TEXT NOT NULL, content TEXT NOT NULL,
                    source_post TEXT, archived INTEGER NOT NULL DEFAULT 0,
                    created DOUBLE PRECISION NOT NULL, UNIQUE(owner, source_post));
                CREATE TABLE IF NOT EXISTS posts (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL,
                    book_id TEXT NOT NULL, title TEXT NOT NULL, description TEXT NOT NULL,
                    content TEXT NOT NULL, fingerprint TEXT UNIQUE NOT NULL,
                    active INTEGER NOT NULL DEFAULT 1, created DOUBLE PRECISION NOT NULL);
                CREATE TABLE IF NOT EXISTS acquisitions (
                    owner TEXT NOT NULL, post_id TEXT NOT NULL, created DOUBLE PRECISION NOT NULL,
                    PRIMARY KEY(owner, post_id));
                CREATE TABLE IF NOT EXISTS session_owners (
                    session_id TEXT PRIMARY KEY, owner TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS upload_owners (
                    book_id TEXT PRIMARY KEY, owner TEXT NOT NULL, created DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS native_workspaces (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, name TEXT NOT NULL,
                    preferences TEXT NOT NULL, created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL);
                CREATE INDEX IF NOT EXISTS native_workspace_owner ON native_workspaces(owner);
                CREATE TABLE IF NOT EXISTS native_resources (
                    id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES native_workspaces(id) ON DELETE CASCADE,
                    book_id TEXT NOT NULL, structure_json TEXT, session_id TEXT,
                    revision INTEGER NOT NULL DEFAULT 0, created DOUBLE PRECISION NOT NULL,
                    UNIQUE(workspace_id,book_id));
                CREATE TABLE IF NOT EXISTS native_session_context (
                    session_id TEXT PRIMARY KEY, resource_id TEXT NOT NULL,
                    structure_json TEXT NOT NULL, items_json TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS native_progress (
                    resource_id TEXT PRIMARY KEY REFERENCES native_resources(id) ON DELETE CASCADE,
                    revision INTEGER NOT NULL, payload TEXT NOT NULL, updated DOUBLE PRECISION NOT NULL);
                CREATE TABLE IF NOT EXISTS native_mutations (
                    resource_id TEXT NOT NULL REFERENCES native_resources(id) ON DELETE CASCADE,
                    mutation_id TEXT NOT NULL, PRIMARY KEY(resource_id,mutation_id));
                CREATE TABLE IF NOT EXISTS native_selection (
                    owner TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, resource_id TEXT);
                CREATE TABLE IF NOT EXISTS native_learner_preferences (
                    owner TEXT PRIMARY KEY, payload TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS native_catalog_practice (
                    resource_id TEXT NOT NULL REFERENCES native_resources(id) ON DELETE CASCADE,
                    event_id TEXT NOT NULL, payload TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
                    PRIMARY KEY(resource_id,event_id));
                CREATE TABLE IF NOT EXISTS native_design_overrides (
                    workspace_id TEXT PRIMARY KEY REFERENCES native_workspaces(id) ON DELETE CASCADE,
                    revision INTEGER NOT NULL, payload TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS native_daily_plans (
                    workspace_id TEXT NOT NULL REFERENCES native_workspaces(id) ON DELETE CASCADE,
                    day TEXT NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(workspace_id,day));
                CREATE TABLE IF NOT EXISTS native_task_completions (
                    workspace_id TEXT NOT NULL REFERENCES native_workspaces(id) ON DELETE CASCADE,
                    event_id TEXT NOT NULL, task_id TEXT NOT NULL, created DOUBLE PRECISION NOT NULL,
                    PRIMARY KEY(workspace_id,event_id));
                CREATE TABLE IF NOT EXISTS native_design_adjustments (
                    workspace_id TEXT NOT NULL REFERENCES native_workspaces(id) ON DELETE CASCADE,
                    adjustment_id TEXT NOT NULL, payload TEXT NOT NULL,
                    PRIMARY KEY(workspace_id,adjustment_id));
CREATE TABLE IF NOT EXISTS accounts(owner TEXT PRIMARY KEY,email TEXT NOT NULL UNIQUE,stage TEXT NOT NULL,interests TEXT NOT NULL,goal TEXT NOT NULL,is_demo INTEGER NOT NULL DEFAULT 0,created DOUBLE PRECISION NOT NULL);
                CREATE TABLE IF NOT EXISTS account_sessions(token_hash TEXT PRIMARY KEY,owner TEXT NOT NULL,created DOUBLE PRECISION NOT NULL,expires DOUBLE PRECISION NOT NULL);
                CREATE INDEX IF NOT EXISTS account_sessions_owner ON account_sessions(owner);
                CREATE TABLE IF NOT EXISTS email_codes(id TEXT PRIMARY KEY,owner TEXT NOT NULL,email TEXT NOT NULL,purpose TEXT NOT NULL,code_hash TEXT NOT NULL,created DOUBLE PRECISION NOT NULL,expires DOUBLE PRECISION NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,used INTEGER NOT NULL DEFAULT 0,ready INTEGER NOT NULL DEFAULT 0);
                CREATE INDEX IF NOT EXISTS codes_email_time ON email_codes(email,created);
                CREATE TABLE IF NOT EXISTS email_rate(ip_hash TEXT NOT NULL,owner TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
                CREATE INDEX IF NOT EXISTS email_rate_ip ON email_rate(ip_hash,created);
CREATE TABLE IF NOT EXISTS social_users(owner TEXT PRIMARY KEY,public_id TEXT UNIQUE NOT NULL,discoverable INTEGER NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS friendships(lo TEXT NOT NULL,hi TEXT NOT NULL,requester TEXT NOT NULL,status TEXT NOT NULL,updated DOUBLE PRECISION NOT NULL,PRIMARY KEY(lo,hi));
                CREATE TABLE IF NOT EXISTS social_blocks(owner TEXT NOT NULL,target TEXT NOT NULL,PRIMARY KEY(owner,target));
                CREATE TABLE IF NOT EXISTS chat_messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,lo TEXT NOT NULL,hi TEXT NOT NULL,sender TEXT NOT NULL,client_id TEXT NOT NULL,text TEXT NOT NULL,attachment TEXT,request_key TEXT NOT NULL DEFAULT '',created DOUBLE PRECISION NOT NULL,UNIQUE(sender,client_id));
                CREATE INDEX IF NOT EXISTS chat_pair_cursor ON chat_messages(lo,hi,id);
                CREATE INDEX IF NOT EXISTS chat_sender_time ON chat_messages(sender,created);
                CREATE INDEX IF NOT EXISTS chat_lo_cursor ON chat_messages(lo,id);
                CREATE INDEX IF NOT EXISTS chat_hi_cursor ON chat_messages(hi,id);
                CREATE TABLE IF NOT EXISTS chat_reads(owner TEXT NOT NULL,peer TEXT NOT NULL,last_id INTEGER NOT NULL,PRIMARY KEY(owner,peer));
                CREATE TABLE IF NOT EXISTS social_rate(owner TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
                CREATE INDEX IF NOT EXISTS social_rate_time ON social_rate(owner,created);
CREATE TABLE IF NOT EXISTS studio_notes (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, book_id TEXT NOT NULL,
                    revision INTEGER NOT NULL, data TEXT NOT NULL, created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL
                );
                CREATE INDEX IF NOT EXISTS studio_notes_owner ON studio_notes(owner,book_id);
                CREATE TABLE IF NOT EXISTS studio_jobs (
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, book_id TEXT NOT NULL,
                    request_id TEXT NOT NULL, fingerprint TEXT NOT NULL, kind TEXT NOT NULL,
                    status TEXT NOT NULL, data TEXT NOT NULL, result TEXT NOT NULL DEFAULT '{}',
                    provider_id TEXT NOT NULL DEFAULT '', error TEXT NOT NULL DEFAULT '',
                    reserved DOUBLE PRECISION NOT NULL DEFAULT 0, created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL,
                    next_poll DOUBLE PRECISION NOT NULL DEFAULT 0, lease_owner TEXT, lease_expires DOUBLE PRECISION, attempts INTEGER NOT NULL DEFAULT 0, UNIQUE(owner,request_id)
                );
                CREATE INDEX IF NOT EXISTS studio_job_owner ON studio_jobs(owner,book_id,created);
CREATE TABLE IF NOT EXISTS diagnostic_banks (
                    book_id TEXT PRIMARY KEY,
                    structure_fingerprint TEXT NOT NULL,
                    items_json TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL,
                    updated_at DOUBLE PRECISION NOT NULL
                );
                CREATE TABLE IF NOT EXISTS interview_sessions (
                    session_id TEXT PRIMARY KEY,
                    user_id TEXT NOT NULL,
                    book_id TEXT NOT NULL,
                    phase TEXT NOT NULL,
                    revision INTEGER NOT NULL CHECK(revision >= 0),
                    session_json TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL,
                    updated_at DOUBLE PRECISION NOT NULL
                );
                CREATE INDEX IF NOT EXISTS idx_interview_user_book
                    ON interview_sessions(user_id, book_id, updated_at DESC);
                CREATE TABLE IF NOT EXISTS course_bundles (
                    course_id TEXT PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    chapter_id TEXT NOT NULL,
                    version INTEGER NOT NULL CHECK(version >= 1),
                    profile_fingerprint TEXT NOT NULL,
                    source_fingerprint TEXT NOT NULL,
                    bundle_json TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL,
                    UNIQUE(session_id, chapter_id, version)
                );
                CREATE INDEX IF NOT EXISTS idx_course_latest
                    ON course_bundles(session_id, chapter_id, version DESC);
                CREATE TABLE IF NOT EXISTS learning_events (
                    event_id TEXT PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    course_id TEXT NOT NULL,
                    item_id TEXT NOT NULL,
                    event_type TEXT NOT NULL,
                    payload_json TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL
                );
CREATE TABLE IF NOT EXISTS books (
                    book_id TEXT PRIMARY KEY,
                    original_name TEXT NOT NULL,
                    file_path TEXT NOT NULL,
                    source_sha256 TEXT NOT NULL,
                    status TEXT NOT NULL,
                    progress DOUBLE PRECISION NOT NULL CHECK(progress >= 0 AND progress <= 1),
                    current_step TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL,
                    updated_at DOUBLE PRECISION NOT NULL
                );
                CREATE TABLE IF NOT EXISTS ocr_jobs (
                    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    book_id TEXT NOT NULL UNIQUE REFERENCES books(book_id) ON DELETE CASCADE,
                    output_dir TEXT NOT NULL,
                    status TEXT NOT NULL,
                    progress DOUBLE PRECISION NOT NULL CHECK(progress >= 0 AND progress <= 1),
                    current_step TEXT NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0,
                    max_attempts INTEGER NOT NULL CHECK(max_attempts >= 1),
                    available_at DOUBLE PRECISION NOT NULL,
                    lease_owner TEXT,
                    lease_expires_at DOUBLE PRECISION,
                    last_error TEXT,
                    result_json TEXT,
                    created_at DOUBLE PRECISION NOT NULL,
                    updated_at DOUBLE PRECISION NOT NULL,
                    finished_at DOUBLE PRECISION
                );
                CREATE INDEX IF NOT EXISTS idx_ocr_jobs_claim
                    ON ocr_jobs(status, available_at, created_at);
                CREATE TABLE IF NOT EXISTS book_structures (
                    book_id TEXT PRIMARY KEY REFERENCES books(book_id) ON DELETE CASCADE,
                    structure_json TEXT NOT NULL,
                    created_at DOUBLE PRECISION NOT NULL,
                    updated_at DOUBLE PRECISION NOT NULL
                );
CREATE TABLE IF NOT EXISTS reading_doubts (
                id TEXT PRIMARY KEY, owner TEXT NOT NULL, book_id TEXT NOT NULL,
                fingerprint TEXT NOT NULL, question TEXT NOT NULL,
                chapter_id TEXT NOT NULL, chapter_title TEXT NOT NULL,
                excerpt TEXT NOT NULL, pages TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'open', note TEXT NOT NULL DEFAULT '',
                due_at DOUBLE PRECISION NOT NULL, created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL,
                UNIQUE(owner,book_id,fingerprint)
            );
            CREATE INDEX IF NOT EXISTS idx_doubts_owner_book
                ON reading_doubts(owner,book_id,status,due_at);
